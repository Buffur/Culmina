# --- PNGs ------------------------------------------------------------------

def _hex(c):
    c = c.lstrip('#')
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def _arc_points(arc, steps=240):
    a0, a1 = arc['start'], arc['end']
    return [pt(arc['r'], a0 + (a1 - a0) * i / steps) for i in range(steps + 1)]


def _star_points(steps=24):
    start, quads = star_segments()
    pts, cur = [start], start
    for c, e in quads:
        pts += [_qb(cur, c, e, i / steps) for i in range(1, steps + 1)]
        cur = e
    return pts


def png_icon(size, rounded):
    """The icon at `size` px. A legacy icon shows units 14..94 of the canvas
    (the safe zone fills most of it, as launchers did); the field follows
    the visible area's gradient."""
    from PIL import Image, ImageDraw
    up = 4
    big = size * up
    field = Image.new('RGBA', (big, big))
    top, bottom = _hex(ICON['field_top']), _hex(ICON['field_bottom'])
    fd = ImageDraw.Draw(field)
    lo, span = 14, 80
    for y in range(big):
        u = lo + y * span / big           # canvas y
        t = min(1, max(0, (u - 18) / 72))
        fd.line([(0, y), (big, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip(top, bottom)))
    mask = Image.new('L', (big, big), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, big - 1, big - 1],
                                           radius=big * 0.18 if rounded else 0, fill=255)
    img = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    img.paste(field, (0, 0), mask)
    d = ImageDraw.Draw(img)
    s = big / span

    def tr(points):
        return [((x - lo) * s, (y - lo) * s) for x, y in points]

    for arc, colour in ((INNER, ICON['inner']), (OUTER, ICON['orbit'])):
        r = arc['w'] * s / 2
        pts = tr(_arc_points(arc))
        for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
            n = max(1, int(math.hypot(x1 - x0, y1 - y0) / (r / 4)))
            for i in range(n + 1):
                x, y = x0 + (x1 - x0) * i / n, y0 + (y1 - y0) * i / n
                d.ellipse([x - r, y - r, x + r, y + r], fill=_hex(colour))
    d.polygon(tr(_star_points()), fill=_hex(ICON['star']))
    return img.resize((size, size), Image.LANCZOS)


# --- Flutter ---------------------------------------------------------------

def dart_geometry():
    start, quads = star_segments()
    star = ', '.join(f(v) for v in start)
    for c, e in quads:
        star += ', ' + ', '.join(f(v) for v in (*c, *e))

    def col(h):
        return f'Color(0xFF{h.lstrip("#").upper()})'

    surfaces = ''
    for name, c in SURFACES.items():
        surfaces += (f'  static const {name} = CulminaMarkColors(\n'
                     f'    background: {col(c["background"])},\n    orbit: {col(c["orbit"])},\n'
                     f'    inner: {col(c["inner"])},\n    star: {col(c["star"])},\n'
                     f'    glint: {col(c["glint"])},\n    starPeak: {col(c["star_peak"])},\n  );\n\n')
    m = MOTION

    def ms(v):
        return f'Duration(milliseconds: {v})'

    timeline = ('/// The launch gesture (owner, 2026-10-23): times from the moment the\n'
                '/// Flutter mark is the one on screen.\n'
                'abstract final class CulminaLaunchTimeline {\n'
                f'  static const gesture = {ms(m["total"])};\n'
                f'  static const markOut = {ms(m["mark_out"])};\n'
                f'  static const fieldOut = {ms(m["field_out"])};\n'
                f'  static const double starScale = {m["star_scale"]};\n\n'
                '  /// The side of the launch mark\'s 108-unit canvas, in logical\n'
                '  /// pixels, as the Android splash and the launch window draw it.\n'
                f'  static const double canvas = {LAUNCH_CANVAS_DP};\n\n'
                '  /// The phases as fractions of [gesture]: (start, end).\n')
    for k in ('glint_head', 'glint_tail', 'glint_in', 'glint_out', 'star_up', 'star_down'):
        a, b = m[k]
        name = ''.join(w.capitalize() if i else w for i, w in enumerate(k.split('_')))
        timeline += f'  static const {name} = ({a / m["total"]}, {b / m["total"]});\n'
    timeline += '}\n\n'
    return (f'// {GENERATED}\n'
            '// The Culmina mark (R3, refreshed dark, star tips rounded; owner\n'
            '// 2026-10-23): the same geometry as the Android vectors.\n\n'
            "import 'dart:ui';\n\n"
            '/// The mark on the 108-unit adaptive-icon canvas, centre (54, 54).\n'
            '/// Arcs: degrees counter-clockwise from east with y up, drawn\n'
            '/// counter-clockwise from `start` to `end`.\n'
            'abstract final class CulminaMarkGeometry {\n'
            '  static const double canvas = 108;\n'
            f'  static const double outerRadius = {f(OUTER["r"])};\n'
            f'  static const double outerStroke = {f(OUTER["w"])};\n'
            f'  static const double outerStart = {OUTER["start"]};\n'
            f'  static const double outerEnd = {OUTER["end"]};\n'
            f'  static const double innerRadius = {f(INNER["r"])};\n'
            f'  static const double innerStroke = {f(INNER["w"])};\n'
            f'  static const double innerStart = {INNER["start"]};\n'
            f'  static const double innerEnd = {INNER["end"]};\n\n'
            "  /// The star's centre (on the outer orbit, on the opening's axis).\n"
            f'  static const double starX = {STAR["x"]};\n'
            f'  static const double starY = {STAR["y"]};\n\n'
            '  /// The star: a move, then quadratic curves as (control, end) pairs.\n'
            f'  static const List<double> star = [{star}];\n\n'
            '  /// The same star as Android path data (checked against the vectors).\n'
            f"  static const String starPathData = '{star_data()}';\n"
            '}\n\n'
            + timeline +
            '/// The mark\'s colours on one of the app\'s surfaces; [glint] and\n'
            '/// [starPeak] are the launch gesture\'s accents.\n'
            'final class CulminaMarkColors {\n'
            '  const CulminaMarkColors({\n    required this.background,\n    required this.orbit,\n'
            '    required this.inner,\n    required this.star,\n    required this.glint,\n'
            '    required this.starPeak,\n  });\n\n'
            '  final Color background;\n  final Color orbit;\n  final Color inner;\n  final Color star;\n'
            '  final Color glint;\n  final Color starPeak;\n\n'
            f'{surfaces.rstrip()}\n'
            '}\n')


# --- motion demo (design lab only) -----------------------------------------

def demo_html():
    def svg(c):
        return (f'<svg viewBox="18 18 72 72" xmlns="http://www.w3.org/2000/svg">'
                f'<path d="{arc_data(INNER)}" fill="none" stroke="{c["inner"]}" stroke-width="{INNER["w"]}" stroke-linecap="round"/>'
                f'<path class="glint" d="{arc_data(INNER)}" fill="none" stroke="{c["glint"]}" stroke-width="{INNER["w"]}" stroke-linecap="round" pathLength="1" opacity="0"/>'
                f'<path d="{arc_data(OUTER)}" fill="none" stroke="{c["orbit"]}" stroke-width="{OUTER["w"]}" stroke-linecap="round"/>'
                f'<path class="star" d="{star_data()}" fill="{c["star"]}"/></svg>')
    data = json.dumps({'motion': MOTION, 'surfaces': SURFACES, 'star': {'x': STAR['x'], 'y': STAR['y']}})
    marks = ''.join(f'<template id="mark-{k}">{svg(c)}</template>' for k, c in SURFACES.items())
    return (DEMO.replace('{{MARKS}}', marks).replace('{{DATA}}', data)
            .replace('{{GENERATED}}', GENERATED))


_DEMO_TEMPLATE = ROOT / 'design' / 'identity-lab' / 'launch-demo.template.html'
DEMO = _DEMO_TEMPLATE.read_text(encoding='utf-8') if _DEMO_TEMPLATE.exists() else ''


def main():
    write = lambda p, s: (p.parent.mkdir(parents=True, exist_ok=True), p.write_text(s, encoding='utf-8'))
    d = RES / 'drawable'
    write(d / 'ic_launcher_foreground.xml', icon_foreground())
    write(d / 'ic_launcher_background.xml', icon_background())
    write(d / 'ic_launcher_monochrome.xml', icon_monochrome())
    for s in SURFACES:
        write(d / f'splash_mark_{s}.xml', splash_mark(s))
        write(d / f'launch_mark_{s}.xml', launch_mark(s))
        write(d / f'launch_background_{s}.xml', launch_background(s))
    write(d / 'launch_background.xml', launch_background('light'))
    write(RES / 'drawable-night' / 'launch_background.xml', launch_background('dark'))
    # Generated raw colour constants belong in the theme layer. Presentation
    # keeps the geometry/timeline and re-exports the semantic mark palette.
    geometry, colours = dart_geometry().split("/// The mark's colours", 1)
    geometry = geometry.replace("import 'dart:ui';",
                                "export '../../core/theme/culmina_mark_colors.dart';")
    write(ROOT / 'lib/presentation/shared/culmina_mark_geometry.dart', geometry.rstrip() + '\n')
    write(ROOT / 'lib/core/theme/culmina_mark_colors.dart',
          f'// {GENERATED}\n' + "import 'dart:ui';\n\n/// The mark's colours" + colours)
    if DEMO:
        write(ROOT / 'design/identity-lab/launch-demo.html', demo_html())
    for folder, size in [('mipmap-mdpi', 48), ('mipmap-hdpi', 72), ('mipmap-xhdpi', 96),
                         ('mipmap-xxhdpi', 144), ('mipmap-xxxhdpi', 192)]:
        png_icon(size, rounded=True).save(RES / folder / 'ic_launcher.png')
    png_icon(512, rounded=False).save(ROOT / 'assets/branding/icon_512.png')


if __name__ == '__main__':
    main()
