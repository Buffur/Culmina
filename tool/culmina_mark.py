# --- geometry (R3-final, approved 2026-10-17; star tips rounded 2026-10-23) --

CENTRE = (54.0, 54.0)
OUTER = dict(r=22.0, w=6.0, start=72.07, end=367.94)   # the C, light
INNER = dict(r=13.2, w=2.4, start=94.08, end=345.92)   # the second line
STAR = dict(x=70.85, y=39.86, ray=9.6, body=1.54)      # R3's curved star
# Medium rounding: each side keeps its R3 curve, trimmed by this fraction at
# both ends; the tip is closed by a curve whose control point is the old
# sharp tip, and the rays are lengthened so the star keeps its 19.2 span.
TIP_ROUND = 0.14

# --- colours ---------------------------------------------------------------

# The launcher icon: the refreshed dark field, top to bottom of the visible
# area, and the mark on it.
ICON = dict(field_top='#1B2A63', field_bottom='#0B1230',
            orbit='#F5F7FD', inner='#A4B2E2', star='#A3D8FF')
# The mark without its tile, on the app's own surfaces (splash, startup):
# the surface decides the mark's colours, as in the lockup with the name.
# `glint` lights the inner arc in the launch motion; `star_peak` is the
# star's brief accent. Backgrounds are AppColors.light/dark/fieldBackground.
SURFACES = {
    'light': dict(background='#FFFFFF', orbit='#0F1C4D', inner='#6C7FB8', star='#1F7FE5',
                  glint='#1F7FE5', star_peak='#0B5CBF'),
    'dark': dict(background='#191919', orbit='#F5F7FD', inner='#A4B2E2', star='#A3D8FF',
                 glint='#D7ECFF', star_peak='#E2F3FF'),
    # Field: dim reds, the same order of brightness (orbit, star, inner).
    'field': dict(background='#000000', orbit='#990000', inner='#5C0000', star='#850000',
                  glint='#850000', star_peak='#A80000'),
}

# --- launch motion ---------------------------------------------------------
# Owner, 2026-10-23 (second brief): the whole gesture is shown before the
# app opens. The native splash is the still mark; Flutter's launch screen
# takes over with the same mark in the same place and plays the gesture
# (LaunchGate, lib/presentation/shared/launch_gate.dart). Times in ms from
# the moment the Flutter mark is the one on screen:
#   0-150      the complete mark, still
#   150-750    a light runs along the inner arc (its own width and caps)
#   650-1100   the star takes up the accent: lighter and 6 % larger, then back
#   1100-1400  the static mark, read before the app opens
# Then the mark fades on the still opaque launch background, and the
# background fades to the app.
MOTION = dict(
    total=1400,
    glint_head=(150, 700),   # the light's leading end along the arc, 0 -> 1
    glint_tail=(250, 750),   # its trailing end, 0 -> 1
    glint_in=(150, 260),     # opacity 0 -> 1
    glint_out=(620, 750),    # opacity 1 -> 0
    star_up=(650, 880),      # star -> star_peak, scale 1 -> star_scale
    star_down=(880, 1100),   # back to the static star
    star_scale=1.06,
    mark_out=150,            # exit: the mark fades on the launch background
    field_out=150,           # then the launch background fades to the app
)
# The launch mark's on-screen size: Android 12+ draws a splash icon without
# an icon background with its 108-unit canvas on 288 dp (measured on the
# phone); the launch window and Flutter use the same.
LAUNCH_CANVAS_DP = 288


def pt(r, a):
    return (CENTRE[0] + r * math.cos(math.radians(a)), CENTRE[1] - r * math.sin(math.radians(a)))


def f(v):
    s = f'{v:.2f}'.rstrip('0').rstrip('.')
    return '0' if s == '-0' else s


def arc_data(arc):
    x0, y0 = pt(arc['r'], arc['start'])
    x1, y1 = pt(arc['r'], arc['end'])
    large = 1 if (arc['end'] - arc['start']) % 360 > 180 else 0
    r = f(arc['r'])
    return f'M{f(x0)},{f(y0)} A{r},{r} 0 {large} 0 {f(x1)},{f(y1)}'


def _qb(p0, q, p2, t):
    return tuple((1 - t) ** 2 * a + 2 * (1 - t) * t * b + t * t * c for a, b, c in zip(p0, q, p2))


def _sub(p0, q, p2, a, b):
    """The control point of a quadratic's sub-curve on [a, b]."""
    return tuple(x * (1 - a) * (1 - b) + y * ((1 - a) * b + a * (1 - b)) + z * a * b
                 for x, y, z in zip(p0, q, p2))


def _tips(ray, k):
    return [(0, -ray), (ray, 0), (0, ray), (-ray, 0)], [(k, -k), (k, k), (-k, k), (-k, -k)]


def _reach(ray, k, t0):
    tips, ctrl = _tips(ray, k)
    e1 = _qb(tips[3], ctrl[3], tips[0], 1 - t0)
    e2 = _qb(tips[0], ctrl[0], tips[1], t0)
    return -_qb(e1, tips[0], e2, 0.5)[1]


def star_segments():
    """The star as a move and eight quadratic curves, in canvas units."""
    k, t0 = STAR['body'], TIP_ROUND
    ray = STAR['ray']
    for _ in range(40):
        ray *= STAR['ray'] / _reach(ray, k, t0)
    tips, ctrl = _tips(ray, k)
    cx, cy = STAR['x'], STAR['y']

    def at(p):
        return (cx + p[0], cy + p[1])

    sides = []
    for i in range(4):
        p0, q, p2 = tips[i], ctrl[i], tips[(i + 1) % 4]
        sides.append((_qb(p0, q, p2, t0), _sub(p0, q, p2, t0, 1 - t0), _qb(p0, q, p2, 1 - t0)))
    start = at(sides[0][0])
    quads = []
    for i in range(4):
        _, c, e = sides[i]
        quads.append((at(c), at(e)))
        quads.append((at(tips[(i + 1) % 4]), at(sides[(i + 1) % 4][0])))
    return start, quads


def star_data():
    start, quads = star_segments()
    d = f'M{f(start[0])},{f(start[1])}'
    for c, e in quads:
        d += f' Q{f(c[0])},{f(c[1])} {f(e[0])},{f(e[1])}'
    return d + ' Z'


# --- Android vectors -------------------------------------------------------

def _vector(body, comment):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- {comment}\n     {GENERATED} -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f'{body}</vector>\n')


def _paths(c, names=False, glint=None):
    n = (lambda s: f'\n        android:name="{s}"') if names else (lambda s: '')
    out = (f'    <path{n("inner")}\n        android:pathData="{arc_data(INNER)}"\n'
           f'        android:strokeWidth="{f(INNER["w"])}"\n        android:strokeColor="{c["inner"]}"\n'
           f'        android:strokeLineCap="round" />\n')
    if glint:
        out += (f'    <path\n        android:name="glint"\n        android:pathData="{arc_data(INNER)}"\n'
                f'        android:strokeWidth="{f(INNER["w"])}"\n        android:strokeColor="{glint}"\n'
                f'        android:strokeLineCap="round"\n        android:strokeAlpha="0"\n'
                f'        android:trimPathEnd="0" />\n')
    out += (f'    <path{n("orbit")}\n        android:pathData="{arc_data(OUTER)}"\n'
            f'        android:strokeWidth="{f(OUTER["w"])}"\n        android:strokeColor="{c["orbit"]}"\n'
            f'        android:strokeLineCap="round" />\n'
            f'    <path{n("star")}\n        android:pathData="{star_data()}"\n'
            f'        android:fillColor="{c["star"]}" />\n')
    return out


